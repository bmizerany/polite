//go:build ignore

//go:generate go run generate.go

// This program generates oids.go from pg_catalog.pg_type using polite.
//
// It is a trimmed-down descendant of commit
// 77592efc82f82849e1193b1a25165b566f628cf3
// ("oids: add generated pg_catalog type OIDs").
//
// This version keeps only basic, well-known built-in PostgreSQL types and
// their plain array types. It excludes domains, catalog row types,
// pseudotypes, ranges, multiranges, and catalog-ish pg_* entries, except
// pg_lsn, which is kept because it is a practical user-facing type.
package main

import (
	"bytes"
	"context"
	"fmt"
	"go/format"
	"os"
	"strings"
	"text/template"
	"time"
	"unicode"

	"blake.io/polite"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "oidgen:", err)
		os.Exit(1)
	}
}

type oid struct {
	ID      uint32
	Typname string
}

func (o oid) Export() string {
	return exportedName(o.Typname)
}

func (o oid) IsArray() bool {
	return strings.HasPrefix(o.Typname, "_")
}

func run() error {
	oids, err := getOIDs()
	if err != nil {
		return err
	}

	t, err := template.New("oids").Parse(`
// Code generated by "go run generate.go"; DO NOT EDIT.

// Package oids provides PostgreSQL type OIDs for built-in well-known types.
package oids

import "strconv"

// ID is a PostgreSQL type OID.
type ID uint32

const (
{{- range . }}
	{{ .Export }} ID = {{ .ID }} // {{ printf "%q" .Typname }}
{{- end }}
)

var idNames = map[ID]string{
{{- range . }}
	{{ .ID }}: {{ printf "%q" .Typname }},
{{- end }}
}

func (id ID) String() string {
	if s := idNames[id]; s != "" {
		return s
	}
	return unknownIDString(id)
}

func (id ID) IsArray() bool {
	s := idNames[id]
	return len(s) > 0 && s[0] == '_'
}

//go:noinline
func unknownIDString(id ID) string {
	return "oids.ID(" + strconv.FormatUint(uint64(id), 10) + ")"
}
`)
	if err != nil {
		return err
	}

	var b bytes.Buffer
	if err := t.Execute(&b, oids); err != nil {
		return err
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}

	return os.WriteFile("oids.go", src, 0o644)
}

func getOIDs() ([]oid, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	cn, err := polite.Dial(ctx, "dbname=template1 host=localhost port=5432 sslmode=disable", nil)
	if err != nil {
		return nil, err
	}
	defer cn.Close()

	const q = `
		WITH scalar AS (
			SELECT oid, typname
			FROM pg_catalog.pg_type
			WHERE typnamespace = 'pg_catalog'::regnamespace
				AND oid < 10000
				AND typtype = 'b'
				AND typcategory <> 'A'
				AND (typname NOT LIKE 'pg_%' OR typname = 'pg_lsn')
		)
		SELECT oid, typname
		FROM scalar
		UNION ALL
		SELECT t.oid, t.typname
		FROM pg_catalog.pg_type AS t
		JOIN scalar AS s ON t.typelem = s.oid
		WHERE t.typnamespace = 'pg_catalog'::regnamespace
			AND t.oid < 10000
			AND t.typtype = 'b'
			AND t.typcategory = 'A'
			AND left(t.typname, 1) = '_'
		ORDER BY oid
	`

	var oids []oid
	for row, err := range cn.Query(ctx, q) {
		if err != nil {
			return nil, err
		}

		var o oid
		for i := 0; i < row.NumColumns(); i++ {
			col := row.Column(i)
			switch col.Name() {
			case "oid":
				v, err := col.ParseInt()
				if err != nil {
					return nil, fmt.Errorf("parse oid column: %w", err)
				}
				o.ID = uint32(v)
			case "typname":
				o.Typname = col.Text()
			default:
				return nil, fmt.Errorf("unexpected pg_type column %q", col.Name())
			}
		}

		oids = append(oids, o)
	}

	return oids, nil
}

func exportedName(typname string) string {
	var arrays int
	var b strings.Builder
	for part := range strings.SplitSeq(typname, "_") {
		if part == "" {
			arrays++
			continue
		}
		writeNamePart(&b, part)
	}
	for range arrays {
		b.WriteString("Array")
	}
	return b.String()
}

func writeNamePart(b *strings.Builder, part string) {
	start := 0
	for i := range part[1:] {
		if unicode.IsDigit(rune(part[i])) == unicode.IsDigit(rune(part[i+1])) {
			continue
		}
		b.WriteByte(byte(unicode.ToUpper(rune(part[start]))))
		b.WriteString(part[start+1 : i+1])
		start = i + 1
	}
	b.WriteByte(byte(unicode.ToUpper(rune(part[start]))))
	b.WriteString(part[start+1:])
}
