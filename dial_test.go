func TestOpenAuthSCRAM(t *testing.T) {
	t.Parallel()

	mainDSN := startPG(t, withHBA(t, []string{
		"-c", "password_encryption=scram-sha-256",
		"-c", "listen_addresses=127.0.0.1",
	}, `
		# order is paramount; first match takes precedence
		host   all  test  127.0.0.1/32 scram-sha-256
		local  all  all   trust
	`)...)

	func() {
		// Create test user with pass
		cn, err := Dial(context.Background(), mainDSN, nil)
		if err != nil {
			t.Fatal(err)
		}
		defer cn.Close()

		const q = `CREATE USER test WITH PASSWORD 'pass'`
		if err := cn.Exec(context.Background(), q); err != nil {
			t.Fatal(err)
		}
	}()

	mainDSN += " host=127.0.0.1"

	cases := []struct {
		user, pass string
		wantErr    bool
	}{
		{"test", "pass", false},
		{"test", "wrong", true},
		{"wrong", "pass", true},
	}

	for _, tt := range cases {
		t.Run(tt.user+"/"+tt.pass, func(t *testing.T) {
			// connect with password
			dsn := fmt.Sprintf("%s user=%s password=%s", mainDSN, tt.user, tt.pass)

			ctx := context.Background()
			cn, err := Dial(ctx, dsn, nil)
			if cn != nil {
				defer cn.Close()
			}
			if err != nil {
				if tt.wantErr {
					return
				}
				t.Fatal(err)
			}
			if tt.wantErr {
				t.Fatal("expected error")
			}

			if err := cn.Exec(context.Background(), "SELECT 1"); err != nil {
				t.Fatal(err)
			}
		})
	}
}

func TestOpenTLS(t *testing.T) {
	t.Parallel()

	sslrootcert, tlsargs := configureTLSOnly(t)
	base := startPG(t, tlsargs...)

	cases := []struct {
		sslmode string
		sslroot string
		host    string // attempts to connect to unix socket if empty
		wantErr bool
	}{
		{"disable", "", "", false}, //  no  TLS  required  for  local  unix  socket
		{"disable", "", "localhost", true},
		{"require", "", "", true},
		{"require", "", "localhost", true},

		{"verify-full", "", "", true},
		{"verify-full", "", "localhost", true},
		{"verify-full", sslrootcert, "", true},
		{"verify-full", sslrootcert, "localhost", false},
	}

	for _, tc := range cases {
		t.Run(tc.sslmode+"-"+tc.host, func(t *testing.T) {
			dsn := base + " sslmode=" + tc.sslmode
			if tc.host != "" {
				dsn += " host=" + tc.host
			}
			if tc.sslroot != "" {
				dsn += " sslrootcert=" + tc.sslroot
			}

			cn, err := Dial(context.Background(), dsn, nil)
			if err != nil {
				if !tc.wantErr {
					t.Fatal(err)
				}
				return
			}
			defer cn.Close()

			if err := cn.Exec(context.Background(), "SELECT 1"); err != nil {
				t.Fatal(err)
			}
		})
	}
}

func TestOpenTLSSystemRootCert(t *testing.T) {
	t.Parallel()

	sslrootcert, tlsargs := configureTLSOnly(t)
	base := startPG(t, tlsargs...)

	for _, tc := range []struct {
		name     string
		rootcert string
	}{
		{name: "lower", rootcert: "system"},
		{name: "mixed", rootcert: "SysTeM"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			// This cert is generated by tests and is not in the system trust store.
			// If sslrootcert=system is actually honored, verification must fail.
			dsnSystem := base + " host=localhost sslmode=verify-full sslrootcert=" + tc.rootcert
			cn, err := Dial(context.Background(), dsnSystem, nil)
			if err == nil {
				cn.Close()
				t.Fatalf("Dial with sslrootcert=%s unexpectedly succeeded", tc.rootcert)
			}
			if strings.Contains(err.Error(), "failed to read root certificate") ||
				strings.Contains(err.Error(), "open system") {
				t.Fatalf("Dial failed by treating %q as file path: %v", tc.rootcert, err)
			}
			if !strings.Contains(err.Error(), "failed to verify certificate") &&
				!strings.Contains(err.Error(), "unknown authority") &&
				!strings.Contains(err.Error(), "not standards compliant") {
				t.Fatalf("Dial error = %v; want certificate verification failure", err)
			}
		})
	}

	dsnFile := base + " host=localhost sslmode=verify-full sslrootcert=" + sslrootcert
	cn, err := Dial(context.Background(), dsnFile, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer cn.Close()
	if err := cn.Exec(context.Background(), "SELECT 1"); err != nil {
		t.Fatal(err)
	}
}

func TestOpenReadDeadline(t *testing.T) {
	t.Parallel()

	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
	defer cancel()

	ctx = febe.WithTrace(ctx, &febe.Trace{
		ReceivedHeader: func(ctx context.Context, h febe.MessageHeader) {
			cancel()
		},
	})

	var gotConn net.Conn
	cfg := &Config{
		Dial: func(ctx context.Context, network, addr string) (net.Conn, error) {
			cn, err := (&net.Dialer{}).DialContext(ctx, network, addr)
			if err != nil {
				return nil, err
			}
			gotConn = cn
			return cn, nil
		},
	}

	db, err := Dial(ctx, testDSN, cfg)
	if err == nil {
		db.Close()
		t.Fatalf("Dial expected to fail")
	}
	if !errors.Is(err, context.Canceled) {
		t.Fatalf("err = %v; want %v", err, context.DeadlineExceeded)
	}
	if gotConn == nil {
		t.Fatal("expected connection to be dialed")
	}
	if !errors.Is(gotConn.Close(), net.ErrClosed) {
		t.Errorf("gotConn.Close() = %v; want %v", err, net.ErrClosed)
	}
}

